package Day2;

public class data_types {
	
	public static void main(String args[])
	{
		/* ** Data- Types ** */
		
		byte num=-128;   					//Range of Byte is (-128 to -127)
		System.out.println("Byte: "+ num);
		
		short num1=32767;					// Range of Short is (-32768 to 32767)
		System.out.println("Short: "+ num1);
		
		int num2 = 2147483647;				// Range of int is (-2147483648 to 2147483647)
		System.out.println("Int: "+ num2);
		
		long num3 = 751;
		System.out.println("Long: "+ num3);
		
		float num4 = 78;
		System.out.println("Float: "+ num4);
		
		double num5 = 71;
		System.out.println("Double: "+ num5);
		
		char c='e';
		System.out.println("Char: "+ c);
		
		boolean b=true;
		System.out.println("Boolean: "+ b);
		
	}

}
